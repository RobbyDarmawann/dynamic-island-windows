const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('island', {
  setMode: mode => ipcRenderer.send('set-mode', mode),
  queueCommand: (cmd, arg) => ipcRenderer.send('queue-command', cmd, arg),
  quit: () => ipcRenderer.send('quit'),
  openChromeMusic: () => ipcRenderer.send('open-chrome-music'),
  getVolume: () => ipcRenderer.invoke('vol-get'),
  testGemini: payload => ipcRenderer.invoke('test-gemini', payload),
  listGeminiModels: payload => ipcRenderer.invoke('list-gemini-models', payload),
  fetchArtwork: url => ipcRenderer.invoke('fetch-artwork', url),
  setVolume: pct => ipcRenderer.invoke('vol-set', pct),
  setMute: muted => ipcRenderer.invoke('vol-mute', muted),
  volStep: dir => ipcRenderer.invoke('vol-step', dir),
  onHiddenState: cb => ipcRenderer.on('hidden-state', (_e, hidden) => cb(hidden)),
  onTrack: fn => ipcRenderer.on('track', (_e, t) => fn(t)),
  onTrackChanged: fn => ipcRenderer.on('track-changed', (_e, t) => fn(t)),
  onOpenChatScreenshot: fn => ipcRenderer.on('open-chat-screenshot', () => fn()),
  onForceMode: fn => ipcRenderer.on('force-mode', (_e, m) => fn(m)),
  onYTState: fn => ipcRenderer.on('yt-state', (_e, s) => fn(s)),
  getTrack: () => ipcRenderer.invoke('get-track'),
  screenshot: () => ipcRenderer.invoke('screenshot'),
  askGemini: (prompt, imageDataUrl) => ipcRenderer.invoke('ask-gemini', { prompt, imageDataUrl }),
  abortGemini: () => ipcRenderer.send('abort-gemini'),
  onGeminiProgress: cb => ipcRenderer.on('gemini-progress', (_e, p) => cb(p)),
  getLyrics: payload => ipcRenderer.invoke('get-lyrics', payload),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: s => ipcRenderer.invoke('save-settings', s),
});
